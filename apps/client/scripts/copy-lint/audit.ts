import { existsSync, readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import type { Analysis } from "./run.ts";
import { countChars, isExempt, literalCounts, type ScreenDef } from "./lib.ts";

const TARGET = { screen: 12, sheet: 8 };
type Row = {
  id: string;
  kind: "screen" | "sheet";
  catalogue: number;
  literals: number;
  longest: { id: string; chars: number };
  failing: string[];
};

export function auditRows(a: Analysis): Row[] {
  const defs: ScreenDef[] = [...a.cfg.screens];
  const prefixesUsed = new Set(defs.flatMap((d) => d.prefixes ?? []));
  const counts = literalCounts(a.literals);
  const pathUsed = (f: string) =>
    defs.some((d) => (d.paths ?? []).some((p) => f.startsWith(p)));
  for (const k of a.en.keys()) {
    const p = k.split(".")[0];
    if (!prefixesUsed.has(p)) {
      prefixesUsed.add(p);
      defs.push({ id: `(catalogue) ${p}`, prefixes: [p] });
    }
  }
  for (const f of Object.keys(counts))
    if (!pathUsed(f)) {
      const parts = f.split("/");
      const dir = parts[1] === "features" ? parts.slice(0, 3).join("/") : f;
      if (!defs.some((d) => d.paths?.includes(dir)))
        defs.push({ id: `(source) ${dir.replace("src/", "")}`, paths: [dir] });
    }
  return defs.map((d) => {
    const ids = [...a.en.keys()].filter((k) =>
      (d.prefixes ?? []).includes(k.split(".")[0]),
    );
    const lit = Object.entries(counts)
      .filter(([f]) => (d.paths ?? []).some((p) => f.startsWith(p)))
      .reduce((n, [, c]) => n + c, 0);
    let longest = { id: "-", chars: 0 };
    for (const id of ids)
      for (const t of a.en.get(id)!.texts)
        if (countChars(t) > longest.chars)
          longest = { id, chars: countChars(t) };
    const failing = ids.filter(
      (id) => a.violations.en[id] || a.violations.ar[id],
    );
    return {
      id: d.id,
      kind: d.kind ?? "screen",
      catalogue: ids.length,
      literals: lit,
      longest,
      failing,
    };
  });
}

export function renderAudit(a: Analysis, root = process.cwd()): string {
  const rows = auditRows(a).filter((r) => r.catalogue + r.literals > 0);
  const total = rows.reduce((n, r) => n + r.catalogue + r.literals, 0);
  const exempt = [...a.en.keys()].filter((k) => isExempt(k, a.cfg));
  const lines: string[] = [
    "# Copy audit",
    "",
    "Generated by `mise run client:copy-audit` from `apps/client/copy-lint.config.json`, the `messages.ts` catalogues and the literal baseline. Do not edit by hand.",
    "",
    "- Current = English catalogue ids for the screen plus inline literals still outside a catalogue (exact AST counts, one per JSX text node, attribute or label property).",
    `- Target = ${TARGET.screen} distinct visible strings per screen, ${TARGET.sheet} per sheet or dialog. Current counts include every state a screen can show, so the number is an upper bound on what is visible at once; the Playwright counter (\`e2e/copy-budget.spec.ts\`) measures what is actually visible.`,
    "- Failing ids = catalogue ids that break a role limit, the plain-words denylist or the Flesch-Kincaid limit in English or Arabic (these are the ids held in `copy-baseline.json`).",
    "",
    `Totals: ${a.en.size} English catalogue ids, ${a.literals.length} inline literals in ${Object.keys(literalCounts(a.literals)).length} files, ${total} strings across screens.`,
    "",
    "| Screen | Catalogue | Literals | Current | Target | Longest string | Failing ids |",
    "|---|---:|---:|---:|---:|---|---|",
  ];
  for (const r of rows.sort(
    (x, y) => y.catalogue + y.literals - (x.catalogue + x.literals),
  )) {
    const failing = r.failing.length
      ? `${r.failing.length}: ${r.failing
          .slice(0, 4)
          .map((i) => `\`${i}\``)
          .join(", ")}${r.failing.length > 4 ? ", ..." : ""}`
      : "0";
    const longest = r.longest.chars
      ? `${r.longest.chars} (\`${r.longest.id}\`)`
      : "-";
    lines.push(
      `| ${r.id} | ${r.catalogue} | ${r.literals} | ${r.catalogue + r.literals} | ${TARGET[r.kind]} | ${longest} | ${failing} |`,
    );
  }
  const guided = rows.filter((r) =>
    ["onboarding", "learn-path", "courses", "lesson-player"].includes(r.id),
  );
  const g = guided.reduce((n, r) => n + r.catalogue + r.literals, 0);
  lines.push(
    "",
    "## Guided flow (onboarding, first course, first lesson)",
    "",
    `Baseline ${g} strings (${guided.map((r) => `${r.id} ${r.catalogue + r.literals}`).join(", ")}). Target at most ${Math.floor(g * 0.6)} (down 40%).`,
    "",
    ...visibleSection(root),
    "## Exemptions",
    "",
    "Ids matching `exemptKeyPattern` are exempt from role limits, denylist and grade checks (legal, consent, privacy, cost, price, refund, destructive confirmations).",
    "",
    `${exempt.length} exempt ids: ${exempt.map((k) => `\`${k}\``).join(", ") || "none"}.`,
    "",
    "## Literal baseline by file",
    "",
    "| File | Literals |",
    "|---|---:|",
    ...Object.entries(literalCounts(a.literals)).map(
      ([f, n]) => `| ${relative("src", f)} | ${n} |`,
    ),
    "",
  );
  return lines.join("\n");
}

// Visible strings per screen measured by e2e/copy-budget.spec.ts (390 by 844).
function visibleSection(root: string): string[] {
  const file = resolve(root, "e2e/copy-budget.baseline.json");
  if (!existsSync(file)) return [];
  const m: Record<
    string,
    { strings: number; headings: number; labels: number; captions: number }
  > = JSON.parse(readFileSync(file, "utf8"));
  const screens = [...new Set(Object.keys(m).map((k) => k.split(".")[0]))];
  return [
    "## Visible strings at 390 by 844 (Playwright counter)",
    "",
    "Distinct visible text nodes per route, from `apps/client/e2e/copy-budget.baseline.json` (empty-state data, so list screens show their least content). Violations = headings over 4 words or 24 characters, button labels over 2 words or 16 characters, captions over 60 characters (Arabic characters x1.3). Target: at most 12 strings and 0 violations.",
    "",
    "| Route | en strings | en violations (h/l/c) | ar strings | ar violations (h/l/c) | Target |",
    "|---|---:|---|---:|---|---:|",
    ...screens.map((s) => {
      const e = m[`${s}.en`];
      const r = m[`${s}.ar`];
      const f = (x?: typeof e) =>
        x ? `${x.headings}/${x.labels}/${x.captions}` : "-";
      return `| ${s} | ${e?.strings ?? "-"} | ${f(e)} | ${r?.strings ?? "-"} | ${f(r)} | 12 |`;
    }),
    "",
  ];
}
