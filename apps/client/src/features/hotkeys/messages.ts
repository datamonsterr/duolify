export type ShortcutMessage = keyof typeof en;
export function shortcutMessage(locale: Locale, id: ShortcutMessage) {
  const text = (locale === "ar" ? ar : en)[id];
  return locale === "en-XA"
    ? `［${text}${"～".repeat(Math.ceil(text.length * 0.4))}］`
    : text;
}
